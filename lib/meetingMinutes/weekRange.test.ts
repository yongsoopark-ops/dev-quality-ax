import { describe, expect, it } from "vitest";
import { getWeeklyMeetingRange } from "./weekRange";

/**
 * Hotfix Audit(Production KST/UTC 시간대 오차) — getWeeklyMeetingRange는
 * "지금 이 순간"(절대 시각)을 KST 기준 달력 날짜로 바꾼 뒤 그 주의 월~금을
 * 계산한다. 서버 런타임이 UTC(Netlify Production)든 KST(로컬 개발)든 같은
 * 절대 시각에 대해 항상 같은 결과를 내야 한다 — 특히 KST 자정을 넘나드는
 * 순간(UTC 15:00 경계)에서 "오늘"의 요일이 하루 밀리지 않아야 한다.
 *
 * Step(회의록 주간 갱신 기준일 월요일 → 화요일) — 반환하는 범위는 여전히
 * "월~금"이지만, 새 주차로 넘어가는 시점이 월요일에서 화요일로 하루
 * 밀렸다: 월요일에는 아직 "직전 주"(지난주 월~금)를 그대로 가리키고,
 * 화요일이 돼서야 "이번 주"(이번 주 월~금)로 넘어간다. 화~토/일요일의
 * 동작은 예전과 동일하다(이미 그 주가 활성화된 뒤의 나머지 요일이라
 * 영향이 없다) — 그래서 아래 테스트에서 "월요일" 케이스만 기대값이
 * 바뀌었다.
 */
describe("getWeeklyMeetingRange", () => {
  it("월요일(KST) 기준으로는 아직 직전 주의 월~금을 가리킨다(새 주차 기준일은 화요일부터)", () => {
    // 2026-09-07은 월요일. KST 10:00 = UTC 01:00.
    expect(getWeeklyMeetingRange(new Date("2026-09-07T01:00:00Z"))).toEqual({
      start: "2026-08-31",
      end: "2026-09-04",
    });
  });

  it("화요일(KST) 기준으로는 이번 주(새 주차)의 월~금을 반환한다", () => {
    // 2026-09-08은 화요일.
    expect(getWeeklyMeetingRange(new Date("2026-09-08T01:00:00Z"))).toEqual({
      start: "2026-09-07",
      end: "2026-09-11",
    });
  });

  it("주말(토요일, KST)에는 그 주(화요일부터 활성화된 주)의 월~금을 그대로 가리킨다(다음 주로 앞서가지 않는다)", () => {
    // 2026-09-12는 토요일.
    expect(getWeeklyMeetingRange(new Date("2026-09-12T01:00:00Z"))).toEqual({
      start: "2026-09-07",
      end: "2026-09-11",
    });
  });

  it("일요일(KST)에도 그 주의 월~금을 그대로 가리킨다(다음 날 월요일이 와야 비로소 예전 주 취급)", () => {
    // 2026-09-13은 일요일.
    expect(getWeeklyMeetingRange(new Date("2026-09-13T01:00:00Z"))).toEqual({
      start: "2026-09-07",
      end: "2026-09-11",
    });
  });

  it("자정 경계 — KST로는 이미 월요일이 됐지만 UTC로는 아직 일요일인 순간에도 '아직 직전 주'를 정확히 계산한다", () => {
    // UTC 2026-09-06T15:30:00Z = KST 2026-09-07T00:30(월요일) → 새 주차 기준일
    // (화요일) 이전이라 아직 직전 주를 가리켜야 한다. 서버가 UTC로 이 값을
    // 실행했을 때(getDay()류 로컬 접근자를 썼다면) 요일 자체를 잘못 판정했을
    // 상황을 막는 회귀 테스트다(케이스 자체는 유지, 기대값만 새 정책에 맞게
    // 갱신).
    expect(getWeeklyMeetingRange(new Date("2026-09-06T15:30:00Z"))).toEqual({
      start: "2026-08-31",
      end: "2026-09-04",
    });
  });

  it("반대 경계 — KST로는 아직 일요일 23:59인 순간에는 그 주를 그대로 가리킨다", () => {
    // UTC 2026-09-06T14:59:00Z = KST 2026-09-06T23:59(일요일).
    expect(getWeeklyMeetingRange(new Date("2026-09-06T14:59:00Z"))).toEqual({
      start: "2026-08-31",
      end: "2026-09-04",
    });
  });

  it("월말/월초 경계에서도 자연스럽게 이전 달로 넘어간다(화요일 기준)", () => {
    // 2026-09-01은 화요일 → 새 주차 기준일이라 그 주 월요일(2026-08-31)부터의
    // 범위를 바로 반환한다.
    expect(getWeeklyMeetingRange(new Date("2026-09-01T01:00:00Z"))).toEqual({
      start: "2026-08-31",
      end: "2026-09-04",
    });
  });
});
